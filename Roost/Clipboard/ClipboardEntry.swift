import Foundation

/// One thing that was on the clipboard.
///
/// Metadata and text live here, and are what the index on disk holds. Binary
/// payloads -- an image, the RTF and HTML forms of rich text -- are files of
/// their own beside it, named by `payloads`, so loading the history is
/// reading one small JSON file, not every image anybody ever copied.
struct ClipboardEntry: Codable, Equatable, Identifiable {

    enum Kind: String, Codable, CaseIterable {
        case text, url, richText, image, files
    }

    /// A stored binary form of the entry, by the pasteboard type it was read
    /// as and the file it was written to.
    struct Payload: Codable, Equatable {
        let type: String
        let file: String
        let bytes: Int
    }

    let id: UUID
    let kind: Kind
    /// When it was copied. Moved forward when the same thing is copied again,
    /// so a repeat goes back to the top instead of becoming a second row.
    var date: Date
    /// The plain text of a text, URL or rich-text entry; the paths of a files
    /// entry, one per line. nil for an image.
    var text: String?
    /// File URLs, for a files entry.
    var fileURLs: [String]?
    /// Binary forms, written beside the index.
    var payloads: [Payload]
    /// The image's pixel size, where the entry is one.
    var pixelWidth: Int?
    var pixelHeight: Int?
    /// The thumbnail, a file beside the payloads.
    var thumbnail: String?
    var isPinned: Bool
    /// The app that was in front when the copy was seen.
    ///
    /// "In front", not "copied from": the pasteboard does not record who
    /// wrote to it, and an app can write while it is in the background. It
    /// is right for the ordinary case of copying in the app you are using,
    /// and the interface says "while … was in front" rather than claiming
    /// more.
    var sourceBundleID: String?
    var sourceName: String?
    /// The pasteboard types that were present when it was captured, for the
    /// inspector, and to say honestly what a restore will and will not put
    /// back.
    var types: [String]
    /// Everything stored for it: text plus payloads plus thumbnail.
    var byteSize: Int
    /// What identifies the content, for spotting the same copy twice.
    let fingerprint: String

    var pixelSize: String? {
        guard let pixelWidth, let pixelHeight else { return nil }
        return "\(pixelWidth) × \(pixelHeight)"
    }

    /// Every file this entry owns on disk, for deleting it.
    var files: [String] { payloads.map(\.file) + [thumbnail].compactMap { $0 } }

    func payload(_ type: String) -> Payload? { payloads.first { $0.type == type } }
}

/// The pasteboard types this feature reads and writes, by their raw names.
///
/// Raw strings rather than `NSPasteboard.PasteboardType` so the model and its
/// tests do not need AppKit.
enum ClipboardTypes {
    static let string = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let html = "public.html"
    static let url = "public.url"
    static let fileURL = "public.file-url"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let jpeg = "public.jpeg"

    /// Put on everything Roost itself writes back, so the monitor can tell
    /// its own restore from a new copy even if it misses the change count.
    static let restoredMarker = "com.sagar.roost.clipboard.restored"

    /// Types an app adds to say "do not keep this", from the conventions at
    /// nspasteboard.org that password managers and clipboard tools share,
    /// plus the private ones the best-known managers have used.
    ///
    /// `Concealed` is a password or secret; `Transient` is something put on
    /// the clipboard for an instant, by an app pasting on your behalf;
    /// `AutoGenerated` is content no person chose to copy. All three are
    /// skipped, whatever the settings say.
    static let doNotKeep: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        restoredMarker
    ]
}
